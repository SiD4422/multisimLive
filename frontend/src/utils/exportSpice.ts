/**
 * Export the current circuit as a SPICE .cir netlist file download.
 */
export function downloadSpiceNetlist(netlist: string, circuitName: string = 'circuit'): void {
  // Ensure the netlist has a proper title line
  const lines = netlist.trim().split('\n');
  let finalNetlist = netlist.trim();
  if (!lines[0].startsWith('*')) {
    finalNetlist = `* ${circuitName} — Generated by NodeSim (nodesimapp.com)\n` + finalNetlist;
  }

  const blob = new Blob([finalNetlist], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${circuitName.replace(/[^a-zA-Z0-9_-]/g, '_')}.cir`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
